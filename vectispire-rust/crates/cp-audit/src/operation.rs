//! What the audit log records — `common.domain.audit.AuditOperation`, in its declaration order.
//!
//! The column stays a string: an operation removed from this list must not make an old row unreadable, so
//! reading a row never goes through this enum. The *writers* name a variant, which is what stops a typo
//! becoming an entry nobody will ever find by filtering. `reference/audit/operations.txt`, written by the Java
//! side, holds the list and the wire names to Java's.

