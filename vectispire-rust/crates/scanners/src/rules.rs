//! The rules Vectispire places into a scan's workspace — `RulePlacement` — and the ones it ships —
//! `BundledRules`.
//!
//! **Copied, never mounted from where they live.** A bind mount is resolved by the Docker *daemon*:
//! when the agent runs in a container with the socket mounted, a directory of its image is invisible
//! to a sibling scanner. The workspace is the only path both sides see (decision 0006).
//!
//! **Failing is the point.** An operator directory or a rule set the scan names but cannot have
//! **fails** the source-analysis step — absent, the backlog intact — rather than running with the
//! bundled rules alone, which would exit cleanly with fewer findings and resolve everything the
//! operator's rules had found.

use std::fs::File;
use std::io;
use std::path::{Component, Path, PathBuf};
use std::time::SystemTime;

/// Where the operator's rules land: beside the bundled ones, never among them, so an operator file
/// never silently overwrites a bundled one by sharing its name. Free **only because
/// `--no-rewrite-rule-ids` is passed** — without it, this subdirectory would rename every rule id.
pub const OPERATOR_SUBDIR: &str = "operator";

/// The environment variable an operator sets to supply their own rules.
pub const OPERATOR_RULES_VARIABLE: &str = "VECTISPIRE_SEMGREP_RULES_DIR";

/// Why rules could not be placed.
#[derive(Debug, thiserror::Error)]
pub enum RulesError {
    /// `OperatorRulesUnavailableException`: the source-analysis step fails with this sentence.
    #[error("{0}")]
    OperatorRulesUnavailable(String),
    /// The copy itself failed — `UncheckedIOException("could not place rules from …")`.
    #[error("could not place rules from {from}")]
    Copy {
        from: String,
        #[source]
        cause: io::Error,
    },
}

/// One file of an uploaded rule set — `RuleSet.StoredFile`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StoredFile {
    /// `rule-0001.yaml`: generated by the control plane, never taken from the upload.
    pub path: String,
    /// The name the operator uploaded, kept so a rule can be traced back.
    pub original_name: String,
    pub content: String,
}

/// What an executor calls to obtain a rule set it does not hold — on the agent, the control plane's
/// rules route. The error is the sentence the failure carries.
pub type RuleSetProvider<'a> = &'a dyn Fn(&str) -> Result<Vec<StoredFile>, String>;

/// Places rules into a workspace's `rules/` directory.
#[derive(Debug, Clone)]
pub struct RulePlacement {
    bundled: PathBuf,
}

impl RulePlacement {
    /// `bundled`: the tree Vectispire ships — `semgrep/` and `gitleaks/`.
    pub fn new(bundled: impl Into<PathBuf>) -> RulePlacement {
        RulePlacement { bundled: bundled.into() }
    }

    /// Copies the bundled tree into `rules`, the workspace's rules directory.
    ///
    /// Called **before any scanner**: the secrets scanner's configuration has to be in place even when
    /// source analysis is off, or the tool falls back to the scanned repository's own — the target
    /// supplying the rules of its own audit.
    pub fn place_bundled(&self, rules: &Path) -> Result<(), RulesError> {
        copy_tree(&self.bundled, rules)
    }

    /// Merges the operator's rule directory, if one is configured, and says whether it did.
    pub fn place_operator_rules(&self, rules: &Path, directory: Option<&str>) -> Result<bool, RulesError> {
        let configured = directory.map(java_trim).unwrap_or("");
        if configured.is_empty() {
            return Ok(false);
        }
        let source = Path::new(configured);
        if !source.exists() {
            return Err(RulesError::OperatorRulesUnavailable(format!(
                "{OPERATOR_RULES_VARIABLE} points at {configured}, which cannot be read."
            )));
        }
        if !source.is_dir() {
            return Err(RulesError::OperatorRulesUnavailable(format!(
                "{OPERATOR_RULES_VARIABLE} points at {configured}, which is not a directory."
            )));
        }
        copy_tree(source, &operator_directory(rules))?;
        Ok(true)
    }

    /// Places the rule set a task names, and says whether it did.
    ///
    /// An uploaded set **replaces** the environment directory rather than merging with it: the
    /// directory is per executor, so a merged result would differ between two agents and the SAST
    /// backlog would resolve and reappear as they take turns. With no set named, the directory applies.
    pub fn place_rule_set(
        &self,
        rules: &Path,
        content_hash: Option<&str>,
        provider: Option<RuleSetProvider<'_>>,
        environment_directory: Option<&str>,
    ) -> Result<bool, RulesError> {
        let Some(hash) = content_hash.filter(|hash| !hash.chars().all(crate::jackson::is_java_whitespace)) else {
            return self.place_operator_rules(rules, environment_directory);
        };
        let Some(provider) = provider else {
            return Err(RulesError::OperatorRulesUnavailable(format!(
                "This scan requires uploaded rule set {hash}, and this executor has no way to fetch it."
            )));
        };
        let files = provider(hash).map_err(|failure| {
            RulesError::OperatorRulesUnavailable(format!("Rule set {hash} could not be fetched: {failure}"))
        })?;
        if files.is_empty() {
            return Err(RulesError::OperatorRulesUnavailable(format!(
                "Rule set {hash} came back empty; refusing to scan with the bundled rules alone."
            )));
        }
        let directory = operator_directory(rules);
        let written = (|| -> io::Result<()> {
            std::fs::create_dir_all(&directory)?;
            for file in &files {
                // The **basename**, never the path as given: generated by the control plane, but
                // arriving over HTTP on an agent. A last component that is not a plain name (`..`, `/`)
                // is refused rather than resolved.
                let name = match Path::new(&file.path).components().next_back() {
                    Some(Component::Normal(name)) => name.to_owned(),
                    _ => {
                        return Err(io::Error::new(
                            io::ErrorKind::InvalidInput,
                            format!("{} names no file", file.path),
                        ));
                    }
                };
                std::fs::write(directory.join(name), file.content.as_bytes())?;
            }
            Ok(())
        })();
        written.map_err(|error| {
            RulesError::OperatorRulesUnavailable(format!(
                "Rule set {hash} could not be written into the workspace: {error}"
            ))
        })?;
        Ok(true)
    }

    /// The operator's rule directory, from the environment.
    pub fn environment_directory() -> Option<String> {
        std::env::var(OPERATOR_RULES_VARIABLE).ok()
    }
}

/// `String.trim`: every character up to U+0020 off both ends.
fn java_trim(text: &str) -> &str {
    text.trim_matches(|c: char| c <= ' ')
}

fn operator_directory(rules: &Path) -> PathBuf {
    rules.join("semgrep").join(OPERATOR_SUBDIR)
}

/// `Files.walk` and copy: a link is never descended into, and a link to a file is copied as its
/// target's content — as the Java copy does.
fn copy_tree(from: &Path, to: &Path) -> Result<(), RulesError> {
    fn walk(from: &Path, to: &Path) -> io::Result<()> {
        std::fs::create_dir_all(to)?;
        for entry in std::fs::read_dir(from)? {
            let entry = entry?;
            let source = entry.path();
            let target = to.join(entry.file_name());
            let is_link = std::fs::symlink_metadata(&source)?.file_type().is_symlink();
            if source.is_dir() {
                std::fs::create_dir_all(&target)?;
                if !is_link {
                    walk(&source, &target)?;
                }
            } else {
                std::fs::copy(&source, &target)?;
            }
        }
        Ok(())
    }
    walk(from, to).map_err(|cause| RulesError::Copy { from: from.display().to_string(), cause })
}

// --------------------------------------------------------------------------------- bundled rules

/// The rules Vectispire ships, embedded in the binary — the jar's `rules/` on the Java side. Held to
/// the jar's bytes by `reference/sast/bundled-rules/`, which `BundledRulesReferenceSetTest` writes
/// from `BundledRules.contentOf`.
pub const BUNDLED: &[(&str, &[u8])] = &[
    ("gitleaks/gitleaks.toml", include_bytes!("../../../reference/sast/bundled-rules/gitleaks/gitleaks.toml")),
    (
        "semgrep/python/dangerous-eval.yaml",
        include_bytes!("../../../reference/sast/bundled-rules/semgrep/python/dangerous-eval.yaml"),
    ),
];

/// What every process's directory is named after, and all the sweep ever looks at.
pub const PREFIX: &str = "vectispire-bundled-rules-";
/// Held for the process's life inside its directory, beside the tree and never in it.
pub const IN_USE: &str = ".in-use";
/// The tree the scanners are handed; a subdirectory, so the lock is never copied into a workspace.
pub const TREE: &str = "tree";

/// The bundled rules materialised for this process's life; the directory goes when this is dropped.
#[derive(Debug)]
pub struct MaterialisedRules {
    directory: PathBuf,
    tree: PathBuf,
    /// The lock: held as long as the file is open, released by the kernel however the process ends.
    _lock: File,
}

impl MaterialisedRules {
    /// The tree to hand [`RulePlacement::new`].
    pub fn tree(&self) -> &Path {
        &self.tree
    }
}

impl Drop for MaterialisedRules {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.directory);
    }
}

/// Copies the bundled rules to a directory of their own under the temporary directory, after
/// sweeping the ones earlier processes left behind.
///
/// **Each start made one and nothing removed one** on the Java side, until the lock and the sweep:
/// in the composition the temporary directory is the host's work directory, which outlives every
/// container.
pub fn materialise() -> io::Result<MaterialisedRules> {
    materialise_in(&std::env::temp_dir())
}

/// As [`materialise`], under `parent` — the agent's work directory, which is `java.io.tmpdir` on the
/// Java side. **Not `TMPDIR` by default on the agent**: its image is a lone binary with no `/tmp` at
/// all, and the work directory is the one place the process is given to write.
pub fn materialise_in(parent: &Path) -> io::Result<MaterialisedRules> {
    let started = SystemTime::now();
    std::fs::create_dir_all(parent)?;
    let directory = tempfile::Builder::new().prefix(PREFIX).tempdir_in(parent)?.keep();
    let lock = File::create(directory.join(IN_USE))?;
    lock.lock()?;
    if let Some(parent) = directory.parent() {
        sweep(parent, started, &directory);
    }
    let tree = directory.join(TREE);
    materialise_into(&tree)?;
    Ok(MaterialisedRules { directory, tree, _lock: lock })
}

/// Writes the bundled files under `into`.
pub fn materialise_into(into: &Path) -> io::Result<()> {
    for (name, content) in BUNDLED {
        let target = into.join(name);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(target, content)?;
    }
    Ok(())
}

/// Deletes what earlier processes left in `parent`, and nothing else: a directory (never a link to
/// one) named with [`PREFIX`], owned by this process's user, last written before `started`, whose
/// lock no process holds. The lock is what "older than me" cannot say: two agents sharing a
/// temporary directory each start before the other's check.
///
/// `started` is when this process materialised, not when it started — later by the time it took to
/// get here, which only ever keeps a leftover for the next sweep: anything newer is a live process's,
/// and locked.
pub fn sweep(parent: &Path, started: SystemTime, keep: &Path) {
    // This process's user, as the owner of its own directory; none to compare with, nothing swept.
    let Some(owner) = owner_of(keep) else { return };
    let Ok(entries) = std::fs::read_dir(parent) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let named = entry.file_name().to_str().is_some_and(|name| name.starts_with(PREFIX));
        if named && path != keep && abandoned(&path, owner, started) {
            let _ = std::fs::remove_dir_all(&path);
        }
    }
}

fn abandoned(entry: &Path, owner: u32, started: SystemTime) -> bool {
    let Ok(metadata) = std::fs::symlink_metadata(entry) else { return false };
    if !metadata.is_dir() || owner_of(entry) != Some(owner) {
        return false;
    }
    match metadata.modified() {
        Ok(modified) if modified < started => {}
        _ => return false,
    }
    !in_use(&entry.join(IN_USE))
}

/// The owning user of `path`, the link itself and never its target.
#[cfg(unix)]
fn owner_of(path: &Path) -> Option<u32> {
    use std::os::unix::fs::MetadataExt;
    std::fs::symlink_metadata(path).ok().map(|metadata| metadata.uid())
}

#[cfg(not(unix))]
fn owner_of(_path: &Path) -> Option<u32> {
    None
}

fn in_use(lock_file: &Path) -> bool {
    let Ok(metadata) = std::fs::symlink_metadata(lock_file) else { return false };
    if !metadata.is_file() {
        return false;
    }
    let Ok(file) = File::options().write(true).open(lock_file) else { return false };
    match file.try_lock() {
        Ok(()) => {
            let _ = file.unlock();
            false
        }
        Err(_) => true,
    }
}
